const STORAGE_KEY = "sonnerstudio.lang";

export function getLang(): Lang {
  if (typeof localStorage !== "undefined") {
    const v = localStorage.getItem(STORAGE_KEY) as Lang | null;

    if (v && v in TABLE) {return v;}
  }

  return "de";
}

export function setLang(lang: Lang): void {
  if (typeof localStorage !== "undefined") {
    localStorage.setItem(STORAGE_KEY, lang);
  }
}

export function localizeSpecialist(rawName: string, lang: Lang): string {
  if (!rawName) {
    return "";
  }

  const s = rawName.toLowerCase();

  if (/hermes/.test(s)) {
    return t("agent.hermes", lang);
  }

  if (/plan|konzept|architekt|planner|beplan/.test(s)) {
    return t("specialist.planning", lang);
  }

  if (/bild|image|grafik|visual|vision|design|beeld/.test(s)) {
    return t("specialist.vision", lang);
  }

  if (/audio|stimme|voice|tts|stt|sprach|oudio/.test(s)) {
    return t("specialist.audio", lang);
  }

  if (/code|refactor|implement|patch|build|kode/.test(s)) {
    return t("specialist.code", lang);
  }

  if (/recherch|research|such|search|web|navors/.test(s)) {
    return t("specialist.research", lang);
  }

  if (/analys|review|prüf|pruef|test|verif|analis/.test(s)) {
    return t("specialist.analysis", lang);
  }

  if (/readme|doku|docs|übersetz|uebersetz|translat|i18n|dokument/.test(s)) {
    return t("specialist.docs", lang);
  }

  if (/sekretär|secretary|sekretaresse/.test(s)) {
    return t("module.secretary", lang);
  }

  if (/subagent|sub-agent/.test(s)) {
    return t("module.subagents", lang);
  }

  return rawName;
}

export function localizeModule(mod: string, lang: Lang): string {
  if (mod === "planner") {
    return t("module.planner", lang);
  }

  if (mod === "secretary") {
    return t("module.secretary", lang);
  }

  if (mod === "subagent") {
    return t("module.subagents", lang);
  }

  return mod;
}

export function localizeTrend(trend: string, lang: Lang): string {
  const tLower = (trend || "").toLowerCase();

  if (/steig|ris|styg|haus|aument|cresc|stijg|rosn|alta|раст|yüks|rost|rast|növek|creșt|nous|stig|ανοδ|상승|เพิ่ม|tăng|зрост|עלייה|बढ़|上升|上昇|ارتفاع/.test(tLower)) {
    return t("trend.rising", lang);
  }

  if (/fall|dal|baiss|desc|calo|spad|qued|сниж|düş|kles|csökk|scăd|lask|fald|πτωτ|하락|ลด|giảm|спад|ירידה|घट|下降|انخفاض/.test(tLower)) {
    return t("trend.falling", lang);
  }

  return t("trend.stable", lang);
}
